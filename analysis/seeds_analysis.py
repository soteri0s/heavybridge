#!/usr/bin/env python3
"""Seed-replication analysis for the full-schedule finalists (R0-full, R3g-full).

Reads the per-scene navtest PDMS of results/navtest/<variant>[_sN]/
(perscene_base.csv.gz = k=1 argmax, perscene_k2.csv.gz, perscene_k20.csv.gz).
The original run of each model is seed 1; R*_s2 is seed 2.

Outputs (stdout + seeds_report.md):
  1. Per-seed PDMS table (k=1/2/20) for each model.
  2. Seed spread per model/rank (max-min across seeds).
  3. Paired bootstrap per seed (scene resampling, 20k) for R3gfull - R0full,
     and, when R2bfull runs exist, R2bfull - R0full and R3gfull - R2bfull.
  4. Pooled analysis: per-scene score averaged across seeds, then paired
     bootstrap -- the cleanest single answer to "is the argmax win seed-robust?"
"""
import csv
import gzip
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
NT = os.path.join(HERE, os.pardir, "results", "navtest")
KFILES = {"1": "perscene_base.csv.gz", "2": "perscene_k2.csv.gz", "20": "perscene_k20.csv.gz"}


def scores(path):
    out = {}
    with gzip.open(path, "rt") as f:
        for r in csv.DictReader(f):
            if r["token"] == "average" or not r["token"]:
                continue
            try:
                out[r["token"]] = float(r["score"])
            except (ValueError, KeyError):
                pass
    return out


def find_runs(base):
    """base -> {seed_label: dirname}; the original run is seed 's1' (stock)."""
    runs = {}
    if os.path.isdir(os.path.join(NT, base)):
        runs["s1*"] = base  # stock seed of the original run
    for d in sorted(os.listdir(NT)):
        m = re.fullmatch(re.escape(base) + r"_s(\d+)", d)
        if m:
            runs[f"s{m.group(1)}"] = d
    return runs


def boot_ci(diff, B=20000, seed=0):
    rng = np.random.default_rng(seed)
    n = len(diff)
    bm = np.empty(B)
    for c in range(B // 1000):
        idx = rng.integers(0, n, size=(1000, n))
        bm[c * 1000:(c + 1) * 1000] = 100 * diff[idx].mean(axis=1)
    lo, hi = np.percentile(bm, [2.5, 97.5])
    p = max(float((bm <= 0).mean()), 1.0 / B)
    return 100 * diff.mean(), lo, hi, p


def main():
    lines = []

    def emit(s=""):
        print(s)
        lines.append(s)

    # R2bfull (bounded amortized per-rollout, full schedule) is optional; absent
    # directories simply yield no seeds.
    runs = {m: find_runs(m) for m in ("R3gfull", "R0full", "R2bfull")}
    runs = {m: rr for m, rr in runs.items() if rr or m in ("R3gfull", "R0full")}
    emit("# Seed replication report (auto-generated by seeds_analysis.py)\n")
    for m, rr in runs.items():
        emit(f"{m}: seeds found: {', '.join(rr) or 'NONE'}")
    emit()

    # 1-2: per-seed table + spread
    per = {}  # (model, seed, k) -> dict token->score
    for m, rr in runs.items():
        for s_label, d in rr.items():
            for k, f in KFILES.items():
                path = os.path.join(NT, d, f)
                if os.path.exists(path):
                    per[(m, s_label, k)] = scores(path)

    emit("## Per-seed PDMS (x100)\n")
    emit("| model | seed | k=1 | k=2 | k=20 |")
    emit("|---|---|---|---|---|")
    for m, rr in runs.items():
        for s_label in rr:
            row = [m, s_label]
            for k in ("1", "2", "20"):
                d = per.get((m, s_label, k))
                row.append(f"{100 * np.mean(list(d.values())):.2f}" if d else "--")
            emit("| " + " | ".join(row) + " |")
    emit()

    emit("## Seed spread (max - min across seeds, x100)\n")
    for m, rr in runs.items():
        if len(rr) < 2:
            emit(f"{m}: only one seed present, no spread yet")
            continue
        for k in ("1", "2", "20"):
            vals = [100 * np.mean(list(per[(m, s, k)].values()))
                    for s in rr if (m, s, k) in per]
            if len(vals) >= 2:
                emit(f"{m} k={k}: spread {max(vals) - min(vals):.3f}")
    emit()

    # 3-4: paired bootstraps, per seed and pooled, for every model pair present.
    pairs = [("R3gfull", "R0full"), ("R2bfull", "R0full"), ("R3gfull", "R2bfull")]
    for A, Bm in pairs:
        if A not in runs or Bm not in runs:
            continue
        common = sorted(set(runs[A]) & set(runs[Bm]))
        if not common:
            emit(f"## {A} - {Bm}: no common seeds yet\n")
            continue
        emit(f"## Paired bootstrap {A} - {Bm}, per seed\n")
        for s_label in common:
            for k in ("1", "2", "20"):
                a = per.get((A, s_label, k))
                b = per.get((Bm, s_label, k))
                if not (a and b):
                    continue
                toks = sorted(set(a) & set(b))
                diff = np.array([a[t] - b[t] for t in toks])
                mean, lo, hi, p = boot_ci(diff)
                emit(f"seed {s_label} k={k}: n={len(toks)}  Δ={mean:+.3f}  "
                     f"CI95=[{lo:+.3f},{hi:+.3f}]  one-sided p={p:.4g}")
        emit()
        if len(common) >= 2:
            emit(f"## Pooled across seeds, {A} - {Bm} (per-scene mean over seeds, then paired bootstrap)\n")
            for k in ("1", "2", "20"):
                adicts = [per[(A, s, k)] for s in common if (A, s, k) in per]
                bdicts = [per[(Bm, s, k)] for s in common if (Bm, s, k) in per]
                if not (adicts and bdicts):
                    continue
                toks = set.intersection(*[set(d) for d in adicts + bdicts])
                toks = sorted(toks)
                a = np.mean([[d[t] for t in toks] for d in adicts], axis=0)
                b = np.mean([[d[t] for t in toks] for d in bdicts], axis=0)
                mean, lo, hi, p = boot_ci(a - b)
                emit(f"pooled k={k}: n={len(toks)}  Δ={mean:+.3f}  "
                     f"CI95=[{lo:+.3f},{hi:+.3f}]  one-sided p={p:.4g}")
            emit()

    # worst-anchor degradation per model and seed (k=1 minus k=20), the "loses nothing" signature
    emit("## Degradation best -> worst anchor (k=1 minus k=20, x100; per seed)\n")
    for m, rr in runs.items():
        for s_label in rr:
            a = per.get((m, s_label, "1")); b = per.get((m, s_label, "20"))
            if a and b:
                toks = sorted(set(a) & set(b))
                emit(f"{m} seed {s_label}: {100 * np.mean([a[t] - b[t] for t in toks]):+.3f}")
    emit()

    with open(os.path.join(HERE, "seeds_report.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n[saved to analysis/seeds_report.md]")


if __name__ == "__main__":
    sys.exit(main())
